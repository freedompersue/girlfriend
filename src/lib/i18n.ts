export function t(locale: Locale, key: string, params?: Record<string, string>): string {
  let text = translations[locale]?.[key] || translations.zh[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, v);
    }
  }
  return text;
}
